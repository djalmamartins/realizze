-- Recorrências financeiras do usuário/empresa. Não confundir com a assinatura comercial da plataforma.
CREATE TABLE IF NOT EXISTS finance_recurring_items (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    financial_context_id BIGINT UNSIGNED NOT NULL,
    item_type VARCHAR(24) NOT NULL,
    kind VARCHAR(10) NOT NULL,
    name VARCHAR(160) NOT NULL,
    provider VARCHAR(120) DEFAULT NULL,
    amount_cents BIGINT UNSIGNED NOT NULL,
    frequency VARCHAR(16) NOT NULL,
    next_due_date DATE NOT NULL,
    account_id BIGINT UNSIGNED NOT NULL,
    category_id BIGINT UNSIGNED DEFAULT NULL,
    auto_create TINYINT(1) NOT NULL DEFAULT 1,
    status VARCHAR(12) NOT NULL DEFAULT 'active',
    notes VARCHAR(500) DEFAULT NULL,
    created_by INT UNSIGNED DEFAULT NULL,
    canceled_at DATETIME DEFAULT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    KEY finance_recurring_context_status (financial_context_id, status, next_due_date),
    CONSTRAINT finance_recurring_context_fk FOREIGN KEY (financial_context_id) REFERENCES financial_contexts(id) ON DELETE CASCADE,
    CONSTRAINT finance_recurring_account_fk FOREIGN KEY (account_id) REFERENCES finance_accounts(id) ON DELETE RESTRICT,
    CONSTRAINT finance_recurring_category_fk FOREIGN KEY (category_id) REFERENCES finance_categories(id) ON DELETE SET NULL,
    CONSTRAINT finance_recurring_user_fk FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT finance_recurring_type_check CHECK (item_type IN ('subscription','recurring')),
    CONSTRAINT finance_recurring_kind_check CHECK (kind IN ('income','expense')),
    CONSTRAINT finance_recurring_frequency_check CHECK (frequency IN ('weekly','monthly','quarterly','yearly')),
    CONSTRAINT finance_recurring_status_check CHECK (status IN ('active','paused','canceled')),
    CONSTRAINT finance_recurring_amount_check CHECK (amount_cents > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
