-- Módulo 02: cadastro unificado de clientes e fornecedores.
CREATE TABLE finance_contacts (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    financial_context_id BIGINT UNSIGNED NOT NULL,
    person_type VARCHAR(12) NOT NULL,
    legal_name VARCHAR(180) NOT NULL,
    trade_name VARCHAR(180) DEFAULT NULL,
    social_name VARCHAR(180) DEFAULT NULL,
    document_type VARCHAR(8) DEFAULT NULL,
    document_value VARCHAR(14) DEFAULT NULL,
    state_registration VARCHAR(30) DEFAULT NULL,
    municipal_registration VARCHAR(30) DEFAULT NULL,
    email VARCHAR(254) DEFAULT NULL,
    phone VARCHAR(24) DEFAULT NULL,
    mobile VARCHAR(24) DEFAULT NULL,
    website VARCHAR(255) DEFAULT NULL,
    birth_date DATE DEFAULT NULL,
    postal_code VARCHAR(8) DEFAULT NULL,
    street VARCHAR(180) DEFAULT NULL,
    address_number VARCHAR(30) DEFAULT NULL,
    complement VARCHAR(100) DEFAULT NULL,
    district VARCHAR(100) DEFAULT NULL,
    city VARCHAR(100) DEFAULT NULL,
    state CHAR(2) DEFAULT NULL,
    contact_person VARCHAR(180) DEFAULT NULL,
    notes TEXT DEFAULT NULL,
    is_customer TINYINT(1) NOT NULL DEFAULT 0,
    is_supplier TINYINT(1) NOT NULL DEFAULT 0,
    status VARCHAR(12) NOT NULL DEFAULT 'active',
    created_by INT UNSIGNED DEFAULT NULL,
    updated_by INT UNSIGNED DEFAULT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY finance_contacts_document_unique (financial_context_id, document_type, document_value),
    KEY finance_contacts_listing_index (financial_context_id, status, person_type, legal_name),
    KEY finance_contacts_roles_index (financial_context_id, is_customer, is_supplier),
    CONSTRAINT finance_contacts_context_fk FOREIGN KEY (financial_context_id) REFERENCES financial_contexts(id) ON DELETE CASCADE,
    CONSTRAINT finance_contacts_created_by_fk FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT finance_contacts_updated_by_fk FOREIGN KEY (updated_by) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT finance_contacts_person_check CHECK (person_type IN ('individual','company')),
    CONSTRAINT finance_contacts_status_check CHECK (status IN ('active','inactive')),
    CONSTRAINT finance_contacts_role_check CHECK (is_customer = 1 OR is_supplier = 1)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE finance_contact_audit_logs (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    financial_context_id BIGINT UNSIGNED NOT NULL,
    contact_id BIGINT UNSIGNED NOT NULL,
    action VARCHAR(20) NOT NULL,
    actor_user_id INT UNSIGNED DEFAULT NULL,
    metadata_json JSON DEFAULT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    KEY finance_contact_audit_index (contact_id, created_at),
    CONSTRAINT finance_contact_audit_context_fk FOREIGN KEY (financial_context_id) REFERENCES financial_contexts(id) ON DELETE CASCADE,
    CONSTRAINT finance_contact_audit_contact_fk FOREIGN KEY (contact_id) REFERENCES finance_contacts(id) ON DELETE CASCADE,
    CONSTRAINT finance_contact_audit_user_fk FOREIGN KEY (actor_user_id) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT finance_contact_audit_action_check CHECK (action IN ('created','updated','inactivated','activated'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

