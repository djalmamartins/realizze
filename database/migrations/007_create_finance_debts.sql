-- Módulo Sair das Dívidas (contexto pessoal). Migration aditiva. Valores em centavos,
-- taxas em % ao mês com 4 casas. Nenhuma tabela existente é alterada.
CREATE TABLE IF NOT EXISTS finance_debt_profiles (
    financial_context_id BIGINT UNSIGNED NOT NULL,
    net_income_cents BIGINT UNSIGNED NOT NULL DEFAULT 0,
    essential_expenses_cents BIGINT UNSIGNED NOT NULL DEFAULT 0,
    variable_expenses_cents BIGINT UNSIGNED NOT NULL DEFAULT 0,
    other_commitments_cents BIGINT UNSIGNED NOT NULL DEFAULT 0,
    emergency_reserve_cents BIGINT UNSIGNED NOT NULL DEFAULT 0,
    income_stability VARCHAR(10) NOT NULL DEFAULT 'stable',
    updated_by INT UNSIGNED DEFAULT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (financial_context_id),
    CONSTRAINT finance_debt_profiles_context_fk FOREIGN KEY (financial_context_id) REFERENCES financial_contexts(id) ON DELETE CASCADE,
    CONSTRAINT finance_debt_profiles_user_fk FOREIGN KEY (updated_by) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT finance_debt_profiles_stability_check CHECK (income_stability IN ('stable','variable'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS finance_debts (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    financial_context_id BIGINT UNSIGNED NOT NULL,
    creditor_name VARCHAR(160) NOT NULL,
    institution_id BIGINT UNSIGNED DEFAULT NULL,
    account_id BIGINT UNSIGNED DEFAULT NULL,
    debt_type VARCHAR(30) NOT NULL DEFAULT 'other',
    original_amount_cents BIGINT UNSIGNED DEFAULT NULL,
    balance_cents BIGINT UNSIGNED NOT NULL,
    monthly_rate DECIMAL(8,4) DEFAULT NULL,
    cet_annual DECIMAL(8,4) DEFAULT NULL,
    monthly_payment_cents BIGINT UNSIGNED DEFAULT NULL,
    installments_remaining SMALLINT UNSIGNED DEFAULT NULL,
    next_due_date DATE DEFAULT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'current',
    collateral VARCHAR(16) NOT NULL DEFAULT 'none',
    risk_notes VARCHAR(500) DEFAULT NULL,
    notes VARCHAR(1000) DEFAULT NULL,
    created_by INT UNSIGNED DEFAULT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    archived_at TIMESTAMP NULL DEFAULT NULL,
    PRIMARY KEY (id),
    KEY finance_debts_context_index (financial_context_id, status),
    CONSTRAINT finance_debts_context_fk FOREIGN KEY (financial_context_id) REFERENCES financial_contexts(id) ON DELETE CASCADE,
    CONSTRAINT finance_debts_institution_fk FOREIGN KEY (institution_id) REFERENCES financial_institutions(id) ON DELETE SET NULL,
    CONSTRAINT finance_debts_account_fk FOREIGN KEY (account_id) REFERENCES finance_accounts(id) ON DELETE SET NULL,
    CONSTRAINT finance_debts_user_fk FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT finance_debts_type_check CHECK (debt_type IN ('credit_card','overdraft','personal_loan','payroll_loan','vehicle','mortgage','student','tax','utility','informal','other')),
    CONSTRAINT finance_debts_status_check CHECK (status IN ('current','overdue','negotiating','agreement','paid','cancelled')),
    CONSTRAINT finance_debts_collateral_check CHECK (collateral IN ('none','vehicle','property','payroll','guarantor','other')),
    CONSTRAINT finance_debts_rate_check CHECK (monthly_rate IS NULL OR (monthly_rate >= 0 AND monthly_rate <= 100))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Pagamentos realizados. entry_id aponta para um lançamento já existente (não duplica a obrigação).
CREATE TABLE IF NOT EXISTS finance_debt_payments (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    debt_id BIGINT UNSIGNED NOT NULL,
    financial_context_id BIGINT UNSIGNED NOT NULL,
    amount_cents BIGINT UNSIGNED NOT NULL,
    paid_on DATE NOT NULL,
    entry_id BIGINT UNSIGNED DEFAULT NULL,
    balance_before_cents BIGINT UNSIGNED NOT NULL,
    balance_after_cents BIGINT UNSIGNED NOT NULL,
    notes VARCHAR(500) DEFAULT NULL,
    created_by INT UNSIGNED DEFAULT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY finance_debt_payments_entry_unique (entry_id),
    KEY finance_debt_payments_debt_index (debt_id, paid_on),
    CONSTRAINT finance_debt_payments_debt_fk FOREIGN KEY (debt_id) REFERENCES finance_debts(id) ON DELETE CASCADE,
    CONSTRAINT finance_debt_payments_context_fk FOREIGN KEY (financial_context_id) REFERENCES financial_contexts(id) ON DELETE CASCADE,
    CONSTRAINT finance_debt_payments_entry_fk FOREIGN KEY (entry_id) REFERENCES finance_entries(id) ON DELETE SET NULL,
    CONSTRAINT finance_debt_payments_user_fk FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT finance_debt_payments_amount_check CHECK (amount_cents > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Propostas de negociação e acordos (histórico).
CREATE TABLE IF NOT EXISTS finance_debt_negotiations (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    debt_id BIGINT UNSIGNED NOT NULL,
    financial_context_id BIGINT UNSIGNED NOT NULL,
    status VARCHAR(12) NOT NULL DEFAULT 'proposal',
    origin VARCHAR(10) NOT NULL DEFAULT 'user',
    down_payment_cents BIGINT UNSIGNED NOT NULL DEFAULT 0,
    installments SMALLINT UNSIGNED NOT NULL DEFAULT 1,
    installment_cents BIGINT UNSIGNED NOT NULL DEFAULT 0,
    first_due_date DATE DEFAULT NULL,
    balance_at_proposal_cents BIGINT UNSIGNED NOT NULL,
    notes VARCHAR(1000) DEFAULT NULL,
    created_by INT UNSIGNED DEFAULT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    KEY finance_debt_negotiations_debt_index (debt_id, created_at),
    CONSTRAINT finance_debt_negotiations_debt_fk FOREIGN KEY (debt_id) REFERENCES finance_debts(id) ON DELETE CASCADE,
    CONSTRAINT finance_debt_negotiations_context_fk FOREIGN KEY (financial_context_id) REFERENCES financial_contexts(id) ON DELETE CASCADE,
    CONSTRAINT finance_debt_negotiations_user_fk FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT finance_debt_negotiations_status_check CHECK (status IN ('proposal','sent','accepted','rejected','broken','completed')),
    CONSTRAINT finance_debt_negotiations_origin_check CHECK (origin IN ('user','creditor')),
    CONSTRAINT finance_debt_negotiations_installments_check CHECK (installments BETWEEN 1 AND 420)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
